"""G-code pre-flight: each check fires on a minimal file and stays quiet on a clean one."""
import json

import pytest

from app.gcode_preflight import MAX_BYTES, PreflightError, analyze

CLEAN = """; generated by SnapmakerOrca 2.2.1 on 2026-11-01
; nozzle_diameter = 0.4,0.4,0.4,0.4
M140 S60
M104 S220 T0
G28
T0
G1 X10 Y10 F3000
G1 X20 Y10 E1.2
M104 S0
"""


def by_id(res):
    return {c["id"]: c for c in res["checks"]}


def run(text, name="part.gcode"):
    return by_id(analyze(text.encode(), name))


def test_clean_file_has_no_fail_or_warn():
    res = analyze(CLEAN.encode(), "part.gcode")
    assert res["summary"]["FAIL"] == 0 and res["summary"]["WARN"] == 0
    assert res["slicer"] == {"name": "SnapmakerOrca", "version": "2.2.1"}
    assert by_id(res)["nozzle_diameters"]["status"] == "INFO"


def test_decimal_comma_fails_with_catalog_code():
    c = run(CLEAN + "G1 X10,5 Y3 E0,2\n")["decimal_comma"]
    assert c["status"] == "FAIL" and c["code"] == "0003-0529-0000-0001" and c["code_title"] == "Gcode Error" and c["evidence"]["count"] == 1


def test_old_orca_named_in_decimal_comma_detail():
    c = run(CLEAN.replace("2.2.1", "2.1.1") + "G1 X1,5\n")["decimal_comma"]
    assert "older than 2.1.2" in c["detail"]


def test_m28_m30():
    c = run(CLEAN + "M29\n")["m28_m30"]
    assert c["status"] == "FAIL" and c["code"] == "0001-0531-0000-0002"


def test_unknown_toolhead():
    c = run(CLEAN + "T4\nG1 X1 E1\n")["unknown_toolhead"]
    assert c["status"] == "FAIL" and c["code"] == "0003-0523-0000-0006"


def test_nozzle_over_300():
    assert run(CLEAN + "M109 S320 T1\n")["nozzle_temp_range"]["status"] == "FAIL"
    assert run(CLEAN + "SET_HEATER_TEMPERATURE HEATER=extruder TARGET=305\n")["nozzle_temp_range"]["status"] == "FAIL"


def test_bed_ranges():
    assert run(CLEAN + "M190 S115\n")["bed_temp_range"]["status"] == "FAIL"
    assert run(CLEAN + "M140 S105\n")["bed_temp_range"]["status"] == "WARN"


def test_bed_zero_only_before_first_extrusion():
    assert run("G28\nM140 S0\nG1 X1 E1\n")["bed_zero"]["status"] == "WARN"
    assert run("G28\nG1 X1 E1\nM140 S0\n")["bed_zero"]["status"] == "PASS"


def test_homing_cases():
    assert run("G1 X1 Y1\n")["homing_first"]["status"] == "WARN"
    assert run("START_PRINT\nG1 X1 Y1\n")["homing_first"]["status"] == "UNKNOWN"
    assert run("G28\nG1 X1\n")["homing_first"]["status"] == "PASS"


def test_mixed_nozzles():
    c = run(CLEAN.replace("0.4,0.4,0.4,0.4", "0.4,0.4,0.6,0.4"))["nozzle_diameters"]
    assert c["status"] == "WARN" and "[0.4, 0.6]" in c["detail"]


def test_hash_filename_and_name_not_echoed():
    res = analyze(CLEAN.encode(), "#secret.gcode")
    assert by_id(res)["filename_hash"]["status"] == "WARN"
    assert "secret" not in json.dumps(res)


def test_evidence_is_capped():
    res = run(CLEAN + "G1 X1,1\n" * 50)["decimal_comma"]
    assert res["evidence"]["count"] == 50 and len(res["evidence"]["lines"]) == 5


def test_deterministic():
    assert json.dumps(analyze(CLEAN.encode(), "a"), sort_keys=True) == json.dumps(analyze(CLEAN.encode(), "a"), sort_keys=True)


@pytest.mark.parametrize("kind,code", [("empty", "EMPTY"), ("blank", "EMPTY"), ("binary", "NOT_TEXT"), ("huge", "TOO_LARGE")])
def test_refused(kind, code):
    data = {"empty": lambda: b"", "blank": lambda: b"   "+bytes([10]), "binary": lambda: bytes([0,1])+b"binary", "huge": lambda: b"x" * (MAX_BYTES + 1)}[kind]()
    with pytest.raises(PreflightError) as e:
        analyze(data)
    assert e.value.code == code


def test_invalid_utf8_does_not_crash():
    assert analyze(b"G28\n; \xff\xfe bad bytes\nG1 X1 E1\n")["file"]["lines"] == 3


def test_api_route(tmp_path):
    from fastapi.testclient import TestClient

    from app.api import create_app

    c = TestClient(create_app(str(tmp_path / "t.sqlite3")), base_url="http://127.0.0.1", headers={"X-U1D": "1"})
    ok = c.post("/api/v1/preflight/gcode?name=part.gcode", content=(CLEAN + "G1 X1,5\n").encode())
    assert ok.status_code == 200 and ok.json()["summary"]["FAIL"] == 1
    bad = c.post("/api/v1/preflight/gcode", content=b"")
    assert bad.status_code == 422 and bad.json()["detail"]["code"] == "EMPTY"
