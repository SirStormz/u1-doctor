def test_3mf_single_plate_is_unchanged():
    settings = b'{"filament_type": ["PLA"]}'
    res = analyze_3mf(make_3mf({**MODEL, "Metadata/plate_1.gcode": CLEAN.encode(), "Metadata/project_settings.config": settings}), "p.3mf")
    alone = analyze(CLEAN.encode(), "p.3mf", {"filament_type": "PLA"})
    assert {k: res[k] for k in alone} == alone
    assert res["source"] == {"kind": "3mf", "entry": "Metadata/plate_1.gcode", "plates": 1, "settings": True}
    (p,) = res["plates"]
    assert p["plate"] == 1 and p["refused"] is None and p["checks"] == alone["checks"] and res["combined"] == {"plates": 1, "refused": 0, "summary": alone["summary"]}


def test_3mf_every_plate_is_checked_with_its_own_result():
    bad = "; generated by SnapmakerOrca 2.2.1\nG1 X1,5 Y2\n"  # decimal comma: the documented 0003-0529-0000-0001 failure
    res = analyze_3mf(make_3mf({**MODEL, "Metadata/plate_2.gcode": bad.encode(), "Metadata/plate_1.gcode": CLEAN.encode()}))
    assert [(p["plate"], p["entry"]) for p in res["plates"]] == [(1, "Metadata/plate_1.gcode"), (2, "Metadata/plate_2.gcode")]
    p1, p2 = res["plates"]
    assert p1["summary"]["FAIL"] == 0 and p2["summary"]["FAIL"] >= 1
    assert res["checks"] == p1["checks"] and res["summary"] == p1["summary"]
    assert res["combined"]["summary"] == {k: p1["summary"][k] + p2["summary"][k] for k in p1["summary"]}
    assert not re.search(r"score|probab|rank", json.dumps(res["combined"]), re.I)


def test_3mf_several_plates_are_ordered_numerically_then_by_name():
    entries = {f"Metadata/plate_{n}.gcode": CLEAN.encode() for n in (10, 2, 1, 3)} | {"Metadata/custom.gcode": CLEAN.encode()}
