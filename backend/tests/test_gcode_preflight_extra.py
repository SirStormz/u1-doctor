def by_id(res):
    return {c["id"]: c for c in res["checks"]}


def run(text, name="part.gcode"):
    return by_id(analyze(text.encode(), name))


def fixture(name):
    return by_id(analyze((GC / name).read_bytes(), name))


def test_first_ten_checks_unchanged_and_new_ones_after_them():
    res = analyze(CLEAN.encode(), "a")
    ids = [c["id"] for c in res["checks"]]
    assert ids[:10] == OLD_IDS
    assert ids[10:] == [i for i in NEW_IDS if i != "prime_tower_bounds"]  # no printable_area in CLEAN: skipped silently
    assert res["summary"]["FAIL"] == 0 and res["summary"]["WARN"] == 0


def test_community_checks_carry_sources_and_date_and_never_a_score():
    res = fixture("synthetic_multitool.gcode")
    for cid in NEW_IDS:
        c = res[cid]
        if cid == "purge_summary":
            assert "community" not in c  # our own computation, not a forum fact
            continue
        assert c["community"]["kind"] == "COMMUNITY_REPORT" and c["community"]["checked"] == CHECKED
        assert c["community"]["sources"] and all(s["url"].startswith("https://forum.snapmaker.com/t/") for s in c["community"]["sources"])
    blob = json.dumps(res).lower()
    assert "probability" not in blob and "score" not in blob


