def test_3mf_total_read_cap_is_shared_across_plates(monkeypatch):
    import app.gcode_preflight as gp
    monkeypatch.setattr(gp, "MAX_TOTAL_BYTES", 3000)
    one = ("G1 X1 Y2 ; " + "abcdefghij" * 3 + "\n") * 40  # about 1.6 kB per plate, ratio well under the cap
    assert len(extract_3mf_plates(make_3mf({"Metadata/plate_1.gcode": one.encode()}))[0]) == 1
    with pytest.raises(PreflightError) as e:
        extract_3mf_plates(make_3mf({"Metadata/plate_1.gcode": one.encode(), "Metadata/plate_2.gcode": one.encode()}))
    assert e.value.code == "ARCHIVE_TOO_LARGE"
    assert MAX_TOTAL_BYTES == 100 * 1024 * 1024


