def test_3mf_refusals():
    with pytest.raises(PreflightError) as e:
        extract_3mf(b"not a zip at all")
    assert e.value.code == "NOT_A_3MF"
    with pytest.raises(PreflightError) as e:
        extract_3mf(make_3mf({"Metadata/plate_1.gcode": b"G28\n"}, encrypt=True))
    assert e.value.code == "ENCRYPTED"
    with pytest.raises(PreflightError) as e:
        extract_3mf(make_3mf({f"f{i}.txt": b"" for i in range(MAX_3MF_ENTRIES + 1)}))
    assert e.value.code == "UNSAFE_ENTRY"
    bomb = make_3mf({"Metadata/plate_1.gcode": b"G1 X1\n" * 2_000_000})  # 12 MB of one repeated line: ratio far above the cap
    with pytest.raises(PreflightError) as e:
        extract_3mf(bomb)
    assert e.value.code == "ARCHIVE_TOO_LARGE"
    with pytest.raises(PreflightError) as e:
        extract_3mf(b"PK" + b"\x00" * (50 * 1024 * 1024))
    assert e.value.code == "ARCHIVE_TOO_LARGE"


