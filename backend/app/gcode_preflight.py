"""Offline G-code pre-flight for the Snapmaker U1: static checks tied to documented firmware/wiki behaviour.

Pure and read-only: the file is only read as text, nothing is executed, sent or stored, and the file name is never echoed.
It is NOT a simulation (U1 Dry Run simulates the firmware): it flags conditions the official wiki and release notes say
cause errors. Macros hide commands, the installed nozzle and the firmware version are unknown here; such limits are reported.
"""
