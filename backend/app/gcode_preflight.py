"""Offline G-code pre-flight for the Snapmaker U1: static checks tied to documented firmware/wiki behaviour.

Pure and read-only: the file is only read as text, nothing is executed, sent or stored, and the file name is never echoed.
It is NOT a simulation (U1 Dry Run simulates the firmware): it flags conditions the official wiki and release notes say
cause errors. Macros hide commands, the installed nozzle and the firmware version are unknown here; such limits are reported.
"""
from __future__ import annotations

import re
from typing import Any

from .knowledge import load_catalog

MAX_BYTES = 64 * 1024 * 1024
MAX_EVIDENCE = 5
WIKI = "https://wiki.snapmaker.com/en/snapmaker_u1/"
REF_KNOWN = {"title": "Known issues and quick fixes", "url": WIKI + "troubleshooting/known_issues_and_quick_fixes"}
REF_CODES = {"title": "U1 error code reference table", "url": WIKI + "troubleshooting/u1_error_codes"}
REF_NOTES = {"title": "U1 firmware release notes", "url": WIKI + "firmware/release_notes"}

NOZZLES = {0.2, 0.4, 0.6, 0.8}
MAX_NOZZLE_C = 300.0   # wiki: settable maximum
MAX_BED_C = 110.0      # wiki: bed valid window -10..110 (error 0003-0526-0000-0000 above)
WARN_BED_C = 100.0     # wiki guides quote 100 degC as the usual maximum

_DEC_COMMA = re.compile(r"\b[XYZEFSIJR]-?\d+,\d+")
_NUM = r"(-?\d+(?:\.\d+)?)"
_S = re.compile(r"\bS" + _NUM)
_TARGET = re.compile(r"\bTARGET=" + _NUM)
_TOOL = re.compile(r"^T(\d+)\b")
_MOVE = re.compile(r"^G[0-3]\b")
_EXTRUDE = re.compile(r"^G[0-3]\b.*\bE" + _NUM)
_GEN = re.compile(r"generated by\s+(.+?)\s+(\d+\.\d+\.\d+)", re.IGNORECASE)
_NOZZLE_CFG = re.compile(r"^;\s*nozzle_diameter\s*=\s*(.+)$")
_MACRO = re.compile(r"^[A-Za-z][A-Za-z0-9]*_[A-Za-z0-9_]+")


class PreflightError(ValueError):
    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code


def _ver(s: str) -> tuple[int, ...]:
    return tuple(int(x) for x in s.split("."))


def _check(cid: str, status: str, title: str, detail: str, lines: list[int], count: int, code: str | None, ref: dict[str, str], **params: Any) -> dict[str, Any]:
    entry = load_catalog()["_by_code"].get(code) if code else None
    return {"id": cid, "status": status, "title": title, "detail": detail,
            "evidence": {"lines": lines[:MAX_EVIDENCE], "count": count},
            "code": code, "code_title": entry["title"] if entry else None, "reference": ref, "params": params}


def _decode(data: bytes) -> list[str]:
    return data.decode("utf-8", errors="replace").splitlines()


def analyze(data: bytes, name: str | None = None) -> dict[str, Any]:
    if len(data) > MAX_BYTES:
        raise PreflightError("TOO_LARGE", "file larger than 64 MiB")
    if not data.strip():
        raise PreflightError("EMPTY", "file is empty")
    if b"\x00" in data[:4096]:
        raise PreflightError("NOT_TEXT", "file does not look like text G-code")
    lines = _decode(data)

    slicer: dict[str, Any] = {"name": None, "version": None}
    nozzle_cfg: list[float] | None = None
    dec_lines: list[int] = []
    over_nozzle: list[int] = []
    over_bed: list[int] = []
    warn_bed: list[int] = []
    zero_bed: list[int] = []
    tools: dict[int, list[int]] = {}
    m28: list[int] = []
    first_move = homing_line = first_extrude = macro_line = None

    for n, raw in enumerate(lines, 1):
        s = raw.strip()
        if not s:
            continue
        if s.startswith(";"):
            if slicer["name"] is None and n <= 200 and (g := _GEN.search(s)):
                slicer = {"name": g.group(1).strip(), "version": g.group(2)}
            if nozzle_cfg is None and (c := _NOZZLE_CFG.match(s)):
                try:
                    nozzle_cfg = [float(x) for x in c.group(1).split(",") if x.strip()]
                except ValueError:
                    nozzle_cfg = None
            continue
        cmd = s.split(";", 1)[0].strip()
        if not cmd:
            continue
        up = cmd.upper()
        if _DEC_COMMA.search(up) and re.match(r"^(G[0-3]|M10[49]|M1[49]0)\b", up):
            dec_lines.append(n)
        if re.match(r"^M(28|29|30)\b", up):
            m28.append(n)
        if (t := _TOOL.match(up)):
            tools.setdefault(int(t.group(1)), []).append(n)
        if up.startswith("G28") and homing_line is None:
            homing_line = n
        if _MOVE.match(up):
            if first_move is None:
                first_move = n
            if first_extrude is None and (e := _EXTRUDE.match(up)) and float(e.group(1)) > 0:
                first_extrude = n
        elif first_move is None and macro_line is None and _MACRO.match(up):
            macro_line = n
        nozzle_set = re.match(r"^M10[49]\b", up) or "SET_HEATER_TEMPERATURE" in up and "EXTRUDER" in up
        bed_set = re.match(r"^M1[49]0\b", up) or "SET_HEATER_TEMPERATURE" in up and "HEATER_BED" in up
        if nozzle_set or bed_set:
            m = _S.search(up) if re.match(r"^M1\d\d\b", up) else _TARGET.search(up)
            if m:
                v = float(m.group(1))
                if nozzle_set and v > MAX_NOZZLE_C:
                    over_nozzle.append(n)
                if bed_set:
                    if v > MAX_BED_C:
                        over_bed.append(n)
                    elif v > WARN_BED_C:
                        warn_bed.append(n)
                    if v == 0 and (first_extrude is None):
                        zero_bed.append(n)

    checks: list[dict[str, Any]] = []
    slic_txt = f"{slicer['name']} {slicer['version']}" if slicer["name"] else None
    orca = bool(slicer["name"] and "orca" in slicer["name"].lower())
    old = orca and _ver(slicer["version"]) < (2, 1, 2)

    # 1 decimal comma
    if dec_lines:
        extra = " The slicer header shows an Orca version older than 2.1.2, the documented cause." if old else \
            " The wiki attributes this to Snapmaker Orca older than 2.1.2 with the interface set to German or French."
        checks.append(_check("decimal_comma", "FAIL", "Decimal commas in motion or temperature commands",
                             "Numbers use a comma as decimal separator, which the printer cannot parse." + extra + " Re-export with a current Snapmaker Orca.",
                             dec_lines, len(dec_lines), "0003-0529-0000-0001", REF_KNOWN, old_orca=old))
    else:
        checks.append(_check("decimal_comma", "PASS", "No decimal commas in motion or temperature commands", "No comma-decimal numbers found.", [], 0, None, REF_KNOWN))

    # 2 unsupported M28-M30
    if m28:
        checks.append(_check("m28_m30", "FAIL", "Unsupported commands M28, M29 or M30",
                             "The official table says these commands are not supported and must be removed.", m28, len(m28), "0001-0531-0000-0002", REF_CODES))
    else:
        checks.append(_check("m28_m30", "PASS", "No M28, M29 or M30", "None of the unsupported commands is present.", [], 0, None, REF_CODES))

    # 3 toolheads
    bad_tools = {t: ls for t, ls in tools.items() if t > 3}
    if bad_tools:
        ls = sorted(x for v in bad_tools.values() for x in v)
        checks.append(_check("unknown_toolhead", "FAIL", "G-code selects a toolhead the printer does not have",
                             f"Tool numbers {sorted(bad_tools)} are used; the U1 has four toolheads (T0 to T3).", ls, len(ls), "0003-0523-0000-0006", REF_CODES, tools=sorted(bad_tools)))
    else:
        used = sorted(tools)
        checks.append(_check("unknown_toolhead", "PASS", "Only T0 to T3 are selected" if used else "No tool selection found",
                             f"Tools used: {used}." if used else "No Tn command; single-tool file or macro-driven selection.", [], 0, None, REF_CODES, tools=used))

    # 4 nozzle temperature
    if over_nozzle:
        checks.append(_check("nozzle_temp_range", "FAIL", f"Nozzle target above {MAX_NOZZLE_C:.0f} degC",
                             "The wiki gives 300 degC as the settable maximum; the firmware rejects higher targets.", over_nozzle, len(over_nozzle), "0003-0523-0000-0036", REF_CODES))
    else:
        checks.append(_check("nozzle_temp_range", "PASS", f"No nozzle target above {MAX_NOZZLE_C:.0f} degC", "All nozzle targets seen are within the documented maximum.", [], 0, None, REF_CODES))

    # 5 bed temperature
    if over_bed:
        checks.append(_check("bed_temp_range", "FAIL", f"Bed target above {MAX_BED_C:.0f} degC",
                             "Above the documented valid window for the heated bed.", over_bed, len(over_bed), "0003-0526-0000-0000", REF_CODES))
    elif warn_bed:
        checks.append(_check("bed_temp_range", "WARN", f"Bed target above {WARN_BED_C:.0f} degC",
                             "Wiki guides quote 100 degC as the usual maximum (and 80 degC for the textured plate): check your plate.", warn_bed, len(warn_bed), None, REF_CODES))
    else:
        checks.append(_check("bed_temp_range", "PASS", "Bed targets within documented limits", "No bed target above 100 degC.", [], 0, None, REF_CODES))

    # 6 bed 0 degC
    if zero_bed:
        checks.append(_check("bed_zero", "WARN", "Bed temperature set to 0 before printing",
                             "Firmware 1.2.0 added a reminder for this case because it can make the first layer fail.", zero_bed, len(zero_bed), None, REF_NOTES))
    else:
        checks.append(_check("bed_zero", "PASS", "No zero bed temperature before printing", "No M140/M190 S0 before the first extrusion.", [], 0, None, REF_NOTES))

    # 7 homing
    if first_move is not None and (homing_line is None or homing_line > first_move):
        if macro_line is not None and macro_line < first_move:
            checks.append(_check("homing_first", "UNKNOWN", "Movement before any visible G28",
                                 "A macro runs before the first move and may home the axes; this static check cannot see inside macros.", [first_move], 1, "0003-0522-0000-0012", REF_CODES))
        else:
            checks.append(_check("homing_first", "WARN", "Movement before homing",
                                 "The first move comes before any G28; the printer refuses moves until homed.", [first_move], 1, "0003-0522-0000-0012", REF_CODES))
    else:
        checks.append(_check("homing_first", "PASS" if first_move is not None else "INFO", "Homing precedes the first move" if first_move is not None else "No movement command found",
                             "G28 appears before the first move." if first_move is not None else "Nothing to check.", [homing_line] if homing_line else [], 1 if homing_line else 0, None, REF_CODES))

    # 8 nozzle diameters
    if nozzle_cfg:
        distinct = sorted(set(nozzle_cfg))
        if len(distinct) > 1:
            checks.append(_check("nozzle_diameters", "WARN", "Mixed nozzle diameters in one job",
                                 f"The slicer config lists diameters {distinct}; the wiki says mixed diameters in one job are not supported and a mismatch with the installed nozzle blocks printing.",
                                 [], 0, None, REF_NOTES, v="mixed", diameters=distinct))
        elif distinct[0] not in NOZZLES:
            checks.append(_check("nozzle_diameters", "WARN", "Unsupported nozzle diameter", f"Diameter {distinct[0]} mm is not one of 0.2, 0.4, 0.6 or 0.8 mm.", [], 0, None, REF_NOTES, v="unsupported", diameter=distinct[0]))
        else:
            checks.append(_check("nozzle_diameters", "INFO", f"Nozzle diameter {distinct[0]} mm declared",
                                 "Compare with Settings > Maintenance > Toolhead Info on the printer: this tool cannot see the installed nozzle.", [], 0, None, REF_NOTES, v="declared", diameter=distinct[0]))
    else:
        checks.append(_check("nozzle_diameters", "UNKNOWN", "Nozzle diameter not found", "No nozzle_diameter entry in the slicer config block.", [], 0, None, REF_NOTES))

    # 9 file name
    if name is not None and name.startswith("#"):
        checks.append(_check("filename_hash", "WARN", "File name starts with #",
                             "Before firmware 2.0.0 such names could shut the system down abnormally; rename the file to be safe.", [], 0, None, REF_NOTES))
    else:
        checks.append(_check("filename_hash", "PASS" if name is not None else "UNKNOWN", "File name has no leading #" if name is not None else "File name not provided",
                             "No issue." if name is not None else "Pass the name to check the firmware 2.0.0 note.", [], 0, None, REF_NOTES))

    # 10 slicer
    if orca:
        checks.append(_check("slicer", "INFO", f"Sliced with {slic_txt}", "Snapmaker Orca output is what the official table recommends for extrusion-related G-code errors.", [], 0, None, REF_CODES, orca=True, name=slicer["name"], version=slicer["version"]))
    elif slic_txt:
        checks.append(_check("slicer", "INFO", f"Sliced with {slic_txt}", "The wiki recommends G-code exported by Snapmaker Orca when extrusion errors point to the file.", [], 0, None, REF_CODES, orca=False, name=slicer["name"], version=slicer["version"]))
    else:
        checks.append(_check("slicer", "UNKNOWN", "Slicer not identified", "No 'generated by' header in the first 200 lines.", [], 0, None, REF_CODES))

    counts = {k: sum(1 for c in checks if c["status"] == k) for k in ("FAIL", "WARN", "PASS", "INFO", "UNKNOWN")}
    return {
        "file": {"bytes": len(data), "lines": len(lines), "name_provided": name is not None},
        "slicer": slicer,
        "checks": checks,
        "summary": counts,
        "limits": [
            "Static text checks, not a simulation: U1 Dry Run simulates the firmware.",
            "Macros can hide commands; the installed nozzle, plate and firmware version are unknown here.",
            "Thresholds come from the official wiki and release notes; the wiki pages do not always agree.",
        ],
    }
